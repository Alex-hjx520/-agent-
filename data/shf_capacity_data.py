def shf_capacity(series: int, refrigerant: str, cond_idx: int, dp_idx: int, is_g: bool = False) -> float:
    """查容量：series 为系列数字；refrigerant 须为对应列序表内的制冷剂名；
    cond_idx 0=工况1 / 1=工况2；dp_idx 0=0.1bar / 1=0.2bar。"""
