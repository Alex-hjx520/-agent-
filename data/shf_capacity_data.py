    refs = _SHFG_REFRIGERANTS if is_g else _SHF_REFRIGERANTS
    ref_idx = refs.index(refrigerant)
    row = table[int(series)]
    return float(row[cond_idx * 10 + ref_idx * 2 + dp_idx])
