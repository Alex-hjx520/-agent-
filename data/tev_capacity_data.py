def available_refs(series: str) -> list:
    """某系列已录入扩展表的制冷剂列表。"""
    return list((_TEV_BLOCKS.get(series.upper()) or {}).keys())


def block_capacity(series: str, refrigerant: str, cond: int, orifice: str, evap_idx: int):
    """查表基值 kW：需保证 orifice 存在、cond 为已录入块、evap_idx∈[0,10]。"""
    ref_blk = (_TEV_BLOCKS.get(series.upper()) or {}).get(refrigerant) or {}
    cond_blk = ref_blk.get(int(cond)) or {}
    row = cond_blk.get(str(orifice))
    if not row or not (0 <= int(evap_idx) < len(EVAP_AXIS)):
        return None
    return float(row[int(evap_idx)])
